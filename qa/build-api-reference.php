<?php
/**
 * Writes the API reference of the wiki from the source: every class, interface and trait of framework/core,
 * framework/core/Snap, framework/database, framework/interfaces (Mcp included) and framework/testing, and every function of
 * framework/helpers, with each public method's signature, doc comment, parameters, return and source line.
 *
 * Run from the project root at each release (after the version is set in framework/core/Framework.php):
 *
 *     php qa/build-api-reference.php ../caligrafy-quill.wiki            # write API-Reference.md and the API-*.md pages
 *     php qa/build-api-reference.php ../caligrafy-quill.wiki --check    # exit 1 when a page is out of date
 *     php qa/build-api-reference.php docs-out/wiki --ref=master         # link the source to a branch instead of the tag
 *     php qa/build-api-reference.php docs-out/wiki --missing             # list the public methods without a doc comment
 *
 * The source is read with tokens (PhpToken), never loaded: no class runs, no Composer package is needed.
 * Doc comments are rendered as written (only @author, @copyright, @version and @package are left out); a method
 * without one says so. Pages it wrote before and no longer writes (a class that was removed) are deleted.
 */

chdir(dirname(__DIR__));

$args = array_slice($argv, 1);
$out = null;
$check = false;
$missing = false;   // --missing: list the public methods and functions that have no doc comment, write nothing
$ref = null;
foreach ($args as $arg) {
    if ($arg === '--check') $check = true;
    elseif ($arg === '--missing') $missing = true;
    elseif (strpos($arg, '--ref=') === 0) $ref = substr($arg, 6);
    elseif ($arg === '-h' || $arg === '--help') { fwrite(STDOUT, usage()); exit(0); }
    elseif ($out === null) $out = rtrim($arg, '/');
    else { fwrite(STDERR, usage()); exit(2); }
}
if ($out === null) { fwrite(STDERR, usage()); exit(2); }
if (!is_dir($out)) {
    if ($check) { fwrite(STDERR, "$out does not exist\n"); exit(1); }
    mkdir($out, 0777, true);
}

function usage()
{
    return "Usage: php qa/build-api-reference.php <wiki folder> [--ref=<git ref>] [--check | --missing]\n";
}

