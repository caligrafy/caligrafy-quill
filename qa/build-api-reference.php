// rendering

function anchor($key)
{
    return strtolower(preg_replace('/[^A-Za-z0-9]+/', '-', $key));
}

/** text for Markdown outside code: < and > as entities so that GitHub does not take them for HTML */
function md_text($text)
{
    $parts = preg_split('/(`[^`]*`)/', $text, -1, PREG_SPLIT_DELIM_CAPTURE);
    foreach ($parts as $i => $part) {
        if ($i % 2 === 1) continue;
        $part = str_replace(array('<', '>'), array('&lt;', '&gt;'), $part);
        $part = preg_replace('/(?<![\\\\\w])\*(?=\S)/', '\\*', $part);   // a lone * would start emphasis
        $part = preg_replace('/(?<=\s|^)_(?=\w)/', '\\_', $part);          // $_SESSION, _construct
        $parts[$i] = $part;
    }
    return implode('', $parts);
}

function table_text($text)
{
    return str_replace('|', '\\|', md_text($text));
}

/** description lines: paragraphs as written, indented lines as code, list items as lists */
function render_description($lines)
{
    // an indented line right under a list item continues that item
    $merged = array();
    $inItem = false;
    foreach ($lines as $line) {
        if ($inItem && preg_match('/^\s{2,}\S/', $line) && !preg_match('/^\s*[-+*] /', $line)) { $merged[count($merged) - 1] .= ' ' . trim($line); continue; }
        $inItem = (bool)preg_match('/^\s*([-+*]|\d+\.) /', $line);
        $merged[] = $line;
    }
    $lines = $merged;
    $out = '';
    $para = array();
    $code = array();
    $list = false;
    $flushPara = function () use (&$para, &$out) {
        if ($para) { $out .= md_text(implode("\n", $para)) . "\n\n"; $para = array(); }
    };
    $flushCode = function () use (&$code, &$out) {
        if ($code) {
            $min = min(array_map(function ($l) { return strlen($l) - strlen(ltrim($l)); }, array_filter($code, 'strlen')));
            $out .= "```\n" . implode("\n", array_map(function ($l) use ($min) { return substr($l, $min); }, $code)) . "\n```\n\n";
            $code = array();
        }
    };
    foreach ($lines as $line) {
        if (trim($line) === '') {
            if ($code) { $code[] = ''; continue; }
            if ($list) { $out .= "\n"; $list = false; }
            $flushPara();
            continue;
        }
        if (preg_match('/^\s{2,}\S/', $line) && !preg_match('/^\s+[-+*] /', $line)) {
            $flushPara();
            if ($list) { $out .= "\n"; $list = false; }
            $code[] = $line;
            continue;
        }
        if ($code) { while ($code && end($code) === '') array_pop($code); $flushCode(); }
        if (preg_match('/^\s*[-+*] /', $line)) { $flushPara(); $out .= md_text(preg_replace('/^\s*[-+*] /', '- ', $line)) . "\n"; $list = true; continue; }
        if ($list) { $out .= "\n"; $list = false; }
        $para[] = trim($line);
    }
    while ($code && end($code) === '') array_pop($code);
    $flushCode();
    $flushPara();
    return rtrim($out, "\n") . "\n\n";
}

function source_link($file, $line, $ref)
{
    return '[' . $file . ':' . $line . '](' . REPO . $ref . '/' . $file . '#L' . $line . ')';
}

function render_class($class, $ref, $level, $withHeading = true)
{
    $h = str_repeat('#', $level);
    $key = preg_replace('/^Caligrafy\\\\/', '', $class['fqcn']);
    $md = '';
    if ($withHeading) $md .= '<a name="' . anchor($key) . '"></a>' . "\n$h " . $class['kind'] . ' ' . $class['fqcn'] . "\n\n";
    else $md .= '<a name="' . anchor($key) . '"></a>' . "\n";
    $decl = $class['kind'] . ' ' . $class['name'];
    if ($class['extends']) $decl .= ' extends ' . implode(', ', $class['extends']);
    if ($class['implements']) $decl .= ' implements ' . implode(', ', $class['implements']);
    $md .= "```php\nnamespace " . preg_replace('/\\\\[^\\\\]+$/', '', $class['fqcn']) . ";\n\n$decl\n```\n\n";
    $md .= 'Source: ' . source_link($class['file'], $class['line'], $ref) . "\n\n";
    if ($class['traits']) $md .= 'Uses: `' . implode('`, `', $class['traits']) . "`\n\n";
    $doc = parse_doc($class['doc']);
    $md .= $doc['lines'] ? render_description($doc['lines']) : "_No doc comment on this class._\n\n";
    $md .= render_tags($doc['tags']);

    $sub = str_repeat('#', $level + 1);
    $methods = public_methods($class);
    if ($class['constants']) {
        $md .= "$sub Constants\n\n";
        foreach ($class['constants'] as $c) {
            $text = strlen($c['text']) > 160 ? substr($c['text'], 0, strpos($c['text'], '=') ?: 40) . '= ...' : $c['text'];
            $d = parse_doc($c['doc'])['lines'];
            $md .= '+ `' . str_replace('`', "'", $text) . '`' . ($d ? ': ' . md_text(implode(' ', array_map('trim', $d))) : '') . "\n";
        }
        $md .= "\n";
    }
    if ($class['properties']) {
        $md .= "$sub Public properties\n\n";
        foreach ($class['properties'] as $p) {
            $text = implode(' ', $p['mods']) . ' ' . (strlen($p['text']) > 160 ? substr($p['text'], 0, strpos($p['text'], '=') ?: 40) . '= ...' : $p['text']);
            $pd = parse_doc($p['doc']);
            $desc = implode(' ', array_map('trim', $pd['lines']));
            foreach ($pd['tags'] as $t) if ($t['tag'] === 'var' && $desc === '') $desc = $t['text'];
            $md .= '+ `' . str_replace('`', "'", trim($text)) . '`' . ($desc !== '' ? ': ' . md_text($desc) : '') . "\n";
        }
        $md .= "\n";
    }
    if ($methods) {
        $md .= "$sub Methods\n\n";
        foreach ($methods as $m) {
            $md .= '+ [`' . (in_array('static', $m['mods']) ? $class['name'] . '::' : '->') . $m['name'] . '()`](#' . anchor($key . '-' . $m['name']) . ')' . "\n";
        }
        $md .= "\n";
        foreach ($methods as $m) $md .= render_function($m, $ref, str_repeat('#', $level + 2), $class);
    } else {
        $md .= "_No public methods._\n\n";
    }
    return $md;
}

function render_tags($tags)
{
    $md = '';
    foreach ($tags as $t) {
        if (in_array($t['tag'], HIDDEN_TAGS)) continue;
        $md .= '+ **@' . $t['tag'] . '** ' . md_text($t['text']) . "\n";
    }
    return $md === '' ? '' : $md . "\n";
}

function render_function($f, $ref, $h, $class)
{
    $key = $class ? preg_replace('/^Caligrafy\\\\/', '', $class['fqcn']) . '-' . $f['name'] : 'fn-' . $f['name'];
    $static = in_array('static', $f['mods']);
    $title = $class ? ($static ? $class['name'] . '::' : '->') . $f['name'] . '()' : $f['name'] . '()';
    $md = '<a name="' . anchor($key) . '"></a>' . "\n$h `$title`\n\n";
    $mods = array_values(array_diff($f['mods'], array('var')));
    if ($class && !array_intersect(array('public', 'protected', 'private'), $mods)) array_unshift($mods, 'public');
    $sig = ($mods ? implode(' ', $mods) . ' ' : '') . 'function ' . ($f['byRef'] ? '&' : '') . $f['name'] . '('
        . implode(', ', array_map(function ($p) { return $p['text']; }, $f['params'])) . ')' . ($f['return'] !== null ? ': ' . $f['return'] : '');
    if (strlen($sig) > 110 && count($f['params']) > 1) {
        $sig = ($mods ? implode(' ', $mods) . ' ' : '') . 'function ' . ($f['byRef'] ? '&' : '') . $f['name'] . "(\n    "
            . implode(",\n    ", array_map(function ($p) { return $p['text']; }, $f['params'])) . "\n)" . ($f['return'] !== null ? ': ' . $f['return'] : '');
    }
    $md .= "```php\n$sig\n```\n\n";
    $doc = parse_doc($f['doc']);
    if ($doc['lines']) $md .= render_description($doc['lines']);
    elseif ($f['doc'] === null) $md .= "_No doc comment._\n\n";

    if ($f['params']) {
        $md .= "**Parameters**\n\n";
        $docParams = array();
        foreach ($doc['params'] as $p) if ($p['name'] !== '') $docParams[$p['name']] = $p;
        $unnamed = array_values(array_filter($doc['params'], function ($p) { return $p['name'] === ''; }));
        foreach ($f['params'] as $idx => $p) {
            $dp = $docParams[$p['name']] ?? ($unnamed[$idx] ?? null);
            $type = $p['type'] ?? ($dp && $dp['type'] !== '' ? $dp['type'] : null);
            $line = '+ `' . ($p['variadic'] ? '...' : '') . $p['name'] . '`';
            if ($type) $line .= ' `' . $type . '`';
            if ($p['default'] !== null) $line .= ', default `' . str_replace('`', "'", $p['default']) . '`';
            if ($dp && $dp['desc'] !== '') $line .= ': ' . md_text($dp['desc']);
            $md .= $line . "\n";
        }
        $md .= "\n";
    }
    if ($f['return'] !== null || $doc['return']) {
        $type = $f['return'] ?? ($doc['return']['type'] ?? '');
        $desc = $doc['return']['desc'] ?? '';
        if ($f['return'] !== null && $doc['return'] && $doc['return']['type'] !== '' && $doc['return']['type'] !== $f['return']) $desc = trim($doc['return']['type'] . ' ' . $desc);
        $md .= '**Returns**' . ($type !== '' ? ' `' . $type . '`' : '') . ($desc !== '' ? ': ' . md_text($desc) : '') . "\n\n";
    }
    $md .= render_tags($doc['tags']);
    $md .= 'Source: ' . source_link($f['file'], $f['line'], $ref) . "\n\n";
    return $md;
}
