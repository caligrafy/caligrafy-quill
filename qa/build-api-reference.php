/**
 * Reads a PHP file with tokens: its classes (with constants, properties and methods) and its functions.
 */
function parse_file($file)
{
    $tokens = array_values(array_filter(PhpToken::tokenize((string)file_get_contents($file)), function ($t) {
        return !$t->is(T_WHITESPACE) && !$t->is(T_COMMENT);
    }));
    $n = count($tokens);
    $namespace = '';
    $classes = array();
    $functions = array();
    $depth = 0;
    $class = null;           // the class being read
    $classDepth = -1;
    $doc = null;             // doc comment waiting for its declaration
    $looseDoc = null;        // the last doc comment of the file not attached to a declaration (a class header)
    $mods = array();
    $headerDoc = null;       // the comment above namespace/use lines: the doc of the file's main class when it has none

    for ($i = 0; $i < $n; $i++) {
        $t = $tokens[$i];
        if ($t->is(T_DOC_COMMENT)) {
            if ($doc !== null && $class === null) $looseDoc = $doc;
            $doc = $t->text;
            continue;
        }
        if ($t->is(T_ATTRIBUTE)) { $i = skip_balanced($tokens, $i, '[', ']'); continue; }
        if ($t->text === '{' || $t->is(T_CURLY_OPEN) || $t->is(T_DOLLAR_OPEN_CURLY_BRACES)) { $depth++; continue; }
        if ($t->text === '}') {
            $depth--;
            if ($class !== null && $depth === $classDepth) { $classes[] = $class; $class = null; $classDepth = -1; }
            continue;
        }
        if ($t->is(T_NAMESPACE) && $class === null && isset($tokens[$i + 1]) && !$tokens[$i + 1]->is(T_NS_SEPARATOR)) {
            $namespace = $tokens[$i + 1]->text === '{' ? '' : ltrim($tokens[$i + 1]->text, '\\');
            if ($doc !== null) { $looseDoc = $doc; $doc = null; }
            continue;
        }
        if ($t->is(array(T_ABSTRACT, T_FINAL, T_READONLY, T_PUBLIC, T_PROTECTED, T_PRIVATE, T_STATIC, T_VAR))) {
            // "static" also starts static::, static fn and return types: only a modifier when a declaration follows
            if ($t->is(T_STATIC) && isset($tokens[$i + 1]) && ($tokens[$i + 1]->is(T_DOUBLE_COLON) || $tokens[$i + 1]->text === '(')) { $doc = null; continue; }
            $mods[] = strtolower($t->text);
            continue;
        }

        // a class, interface, trait or enum (not ::class, not new class)
        if ($t->is(array(T_CLASS, T_INTERFACE, T_TRAIT, T_ENUM)) && $class === null) {
            $prev = $tokens[$i - 1] ?? null;
            if ($prev && ($prev->is(T_DOUBLE_COLON) || $prev->is(T_NEW))) { $mods = array(); continue; }
            if (!isset($tokens[$i + 1]) || !$tokens[$i + 1]->is(T_STRING)) { $mods = array(); continue; }
            $name = $tokens[$i + 1]->text;
            $extends = array(); $implements = array(); $mode = null;
            $j = $i + 2;
            for (; $j < $n && $tokens[$j]->text !== '{'; $j++) {
                if ($tokens[$j]->is(T_EXTENDS)) { $mode = 'extends'; continue; }
                if ($tokens[$j]->is(T_IMPLEMENTS)) { $mode = 'implements'; continue; }
                if ($tokens[$j]->text === ',' || $tokens[$j]->text === ':') continue;
                if ($mode === 'extends') $extends[] = $tokens[$j]->text;
                if ($mode === 'implements') $implements[] = $tokens[$j]->text;
            }
            $classDoc = $doc;
            if ($headerDoc === null && !$classes && $class === null) $headerDoc = $looseDoc;
            $class = array(
                'kind' => $t->is(T_CLASS) ? (in_array('abstract', $mods) ? 'abstract class' : (in_array('final', $mods) ? 'final class' : 'class'))
                    : strtolower($t->text),
                'name' => $name,
                'fqcn' => ($namespace ? $namespace . '\\' : '') . $name,
                'extends' => $extends, 'implements' => $implements, 'traits' => array(),
                'doc' => $classDoc, 'file' => $file, 'line' => $t->line,
                'constants' => array(), 'properties' => array(), 'methods' => array(),
            );
            $doc = null; $looseDoc = null; $mods = array();
            $i = $j;            // on the {
            $classDepth = $depth;
            $depth++;
            continue;
        }

        $inBody = $class !== null && $depth === $classDepth + 1;

        if ($inBody && $t->is(T_USE)) {   // traits
            for ($j = $i + 1; $j < $n && $tokens[$j]->text !== ';' && $tokens[$j]->text !== '{'; $j++) {
                if ($tokens[$j]->text !== ',') $class['traits'][] = $tokens[$j]->text;
            }
            $i = $tokens[$j]->text === '{' ? skip_balanced($tokens, $j, '{', '}') : $j;
            $doc = null; $mods = array();
            continue;
        }

        if ($inBody && $t->is(T_CONST)) {
            $j = $i + 1;
            $type = null;
            if (isset($tokens[$j + 1]) && $tokens[$j + 1]->is(T_STRING) && $tokens[$j]->is(T_STRING)) { $type = $tokens[$j]->text; $j++; }  // typed constants
            $end = statement_end($tokens, $j);
            $text = join_tokens($tokens, $j, $end - 1);
            if (!array_intersect(array('private', 'protected'), $mods)) {
                $class['constants'][] = array('text' => $text, 'doc' => $doc, 'line' => $t->line);
            }
            $i = $end; $doc = null; $mods = array();
            continue;
        }

        if ($inBody && $t->is(T_VARIABLE) && $mods) {   // a property (with or without a type before it)
            $end = statement_end($tokens, $i);
            $text = join_tokens($tokens, $i, $end - 1);
            if (!array_intersect(array('private', 'protected'), $mods)) {
                $class['properties'][] = array('text' => $text, 'mods' => $mods, 'doc' => $doc, 'line' => $t->line);
            }
            $i = $end; $doc = null; $mods = array();
            continue;
        }

        if ($t->is(T_FUNCTION)) {
            $j = $i + 1;
            $byRef = false;
            if (isset($tokens[$j]) && ($tokens[$j]->text === '&' || $tokens[$j]->is(T_AMPERSAND_NOT_FOLLOWED_BY_VAR_OR_VARARG) || $tokens[$j]->is(T_AMPERSAND_FOLLOWED_BY_VAR_OR_VARARG))) { $byRef = true; $j++; }
            if (!isset($tokens[$j]) || $tokens[$j]->text === '(') {   // a closure: skip its body
                $doc = null; $mods = array();
                continue;
            }
            $name = $tokens[$j]->text;
            $open = $j + 1;
            $close = skip_balanced($tokens, $open, '(', ')');
            $params = parse_params($tokens, $open + 1, $close - 1);
            $k = $close + 1;
            $return = null;
            if (isset($tokens[$k]) && $tokens[$k]->text === ':') {
                $s = $k + 1;
                for ($k = $s; $k < $n && $tokens[$k]->text !== '{' && $tokens[$k]->text !== ';'; $k++);
                $return = join_tokens($tokens, $s, $k - 1);
            }
            $entry = array('name' => $name, 'params' => $params, 'return' => $return, 'byRef' => $byRef,
                'doc' => $doc, 'mods' => $mods, 'line' => $t->line, 'file' => $file);
            if ($inBody) {
                $class['methods'][] = $entry;
            } elseif ($class === null) {
                $functions[] = $entry;
            }
            // skip the body (or the ; of an abstract or interface method)
            $i = (isset($tokens[$k]) && $tokens[$k]->text === '{') ? skip_balanced($tokens, $k, '{', '}') : $k;
            $doc = null; $mods = array();
            continue;
        }

        if ($t->text === ';' && $class === null && $doc !== null) { $looseDoc = $doc; $doc = null; }
        if ($inBody) { $doc = null; }
        $mods = array();
    }
    // the header comment goes to the class named like the file (Passkey.php: Passkey, not PasskeyException), else the first
    $main = null;
    foreach ($classes as $idx => $c) if ($c['name'] === basename($file, '.php')) $main = $idx;
    if ($main === null && $classes) $main = 0;
    if ($main !== null && $classes[$main]['doc'] === null && $headerDoc !== null) $classes[$main]['doc'] = $headerDoc;
    return array('classes' => $classes, 'functions' => $functions);
}

function skip_balanced($tokens, $i, $open, $close)
{
    $level = 0;
    for ($n = count($tokens); $i < $n; $i++) {
        $text = $tokens[$i]->text;
        if ($text === $open || ($open === '{' && ($tokens[$i]->is(T_CURLY_OPEN) || $tokens[$i]->is(T_DOLLAR_OPEN_CURLY_BRACES)))
            || ($open === '[' && $tokens[$i]->is(T_ATTRIBUTE))) $level++;
        elseif ($text === $close) { $level--; if ($level === 0) return $i; }
    }
    return $i;
}

/** the index of the ; ending a statement that starts at $i (brackets and parentheses nested) */
function statement_end($tokens, $i)
{
    $level = 0;
    for ($n = count($tokens); $i < $n; $i++) {
        $text = $tokens[$i]->text;
        if ($text === '(' || $text === '[' || $text === '{') $level++;
        elseif ($text === ')' || $text === ']' || $text === '}') $level--;
        elseif ($text === ';' && $level === 0) return $i;
    }
    return $i;
}

function join_tokens($tokens, $from, $to)
{
    $out = '';
    $prev = null;
    for ($i = $from; $i <= $to; $i++) {
        $text = $tokens[$i]->text;
        if ($prev !== null && needs_space($prev, $tokens[$i])) $out .= ' ';
        $out .= $text;
        $prev = $tokens[$i];
    }
    return $out;
}

function needs_space($a, $b)
{
    $noAfter = array('(', '[', '\\', '?', '...', '&', '!', '::', '->', '$', '|', '-');
    $noBefore = array(')', ']', ',', '(', '[', '::', '->', ';', '|');
    if (in_array($a->text, $noAfter)) return $a->text === '-' && !in_array($b->text, array('1', '0')) && !$b->is(T_LNUMBER) && !$b->is(T_DNUMBER);
    if (in_array($b->text, $noBefore)) return false;
    if ($b->text === '\\' || $b->is(T_NS_SEPARATOR)) return !($a->is(T_STRING) || $a->is(T_NAME_QUALIFIED));
    return true;
}

/** parameters: each one's text, type, name and default */
function parse_params($tokens, $from, $to)
{
    $params = array();
    $start = $from;
    $level = 0;
    for ($i = $from; $i <= $to + 1; $i++) {
        $end = $i > $to;
        $text = $end ? ',' : $tokens[$i]->text;
        if (!$end && ($text === '(' || $text === '[' || $text === '{' || $tokens[$i]->is(T_ATTRIBUTE))) $level++;
        if (!$end && ($text === ')' || $text === ']' || $text === '}')) $level--;
        if ($text === ',' && $level === 0) {
            if ($i - 1 >= $start) {
                $type = array(); $name = null; $default = null; $variadic = false; $promoted = array();
                for ($k = $start; $k <= $i - 1; $k++) {
                    $tk = $tokens[$k];
                    if ($tk->is(T_ATTRIBUTE)) { $k = skip_balanced($tokens, $k, '[', ']'); continue; }
                    if ($tk->is(T_VARIABLE)) { $name = $tk->text; continue; }
                    if ($tk->is(T_ELLIPSIS)) { $variadic = true; continue; }
                    if ($tk->is(array(T_PUBLIC, T_PROTECTED, T_PRIVATE, T_READONLY))) { $promoted[] = $tk->text; continue; }
                    if ($tk->text === '=') { $default = join_tokens($tokens, $k + 1, $i - 1); break; }
                    if ($name === null && !($tk->text === '&' || $tk->is(T_AMPERSAND_FOLLOWED_BY_VAR_OR_VARARG) || $tk->is(T_AMPERSAND_NOT_FOLLOWED_BY_VAR_OR_VARARG))) $type[] = $tk->text;
                }
                $params[] = array('text' => join_tokens($tokens, $start, $i - 1), 'type' => $type ? implode('', $type) : null,
                    'name' => $name, 'default' => $default, 'variadic' => $variadic);
            }
            $start = $i + 1;
        }
    }
    return $params;
}

/** a doc comment split into its description lines and its tags */
function parse_doc($doc)
{
    $result = array('lines' => array(), 'params' => array(), 'return' => null, 'tags' => array());
    if ($doc === null) return $result;
    $body = preg_replace('#^/\*\*|\*/$#', '', trim($doc));
    $lines = preg_split('/\R/', $body);
    $current = null;
    foreach ($lines as $line) {
        $line = preg_replace('/^\s*\* ?/', '', $line, 1, $count);
        if (!$count) $line = preg_replace('/^\s+/', '', $line);
        $line = rtrim($line);
        if (preg_match('/^@(\w+)\s*(.*)$/', ltrim($line), $m)) {
            $tag = strtolower($m[1]);
            $rest = trim($m[2]);
            if ($tag === 'param') {
                preg_match('/^(?:(\S+)\s+)?(&?\.{0,3}\$\w+)?\s*(.*)$/s', $rest, $p);
                $type = $p[1] ?? '';
                $name = ltrim($p[2] ?? '', '&.');
                if ($type !== '' && $type[0] === '$' && $name === '') { $name = $type; $type = ''; }
                $result['params'][] = array('type' => $type, 'name' => $name, 'desc' => trim($p[3] ?? ''));
                $current = &$result['params'][count($result['params']) - 1]['desc'];
            } elseif ($tag === 'return' || $tag === 'returns') {
                preg_match('/^(\S+)?\s*(.*)$/s', $rest, $p);
                $result['return'] = array('type' => $p[1] ?? '', 'desc' => trim($p[2] ?? ''));
                $current = &$result['return']['desc'];
            } else {
                $result['tags'][] = array('tag' => $tag, 'text' => $rest);
                $current = &$result['tags'][count($result['tags']) - 1]['text'];
            }
            unset($current);
            $current = null;
            // continuation lines attach to the last tag
            $result['_last'] = $tag;
            continue;
        }
        if (isset($result['_last'])) {
            if (trim($line) === '') continue;
            $last = $result['_last'];
            if ($last === 'param' && $result['params']) $result['params'][count($result['params']) - 1]['desc'] .= ' ' . trim($line);
            elseif (($last === 'return' || $last === 'returns') && $result['return']) $result['return']['desc'] .= ' ' . trim($line);
            elseif ($result['tags']) $result['tags'][count($result['tags']) - 1]['text'] .= ' ' . trim($line);
            continue;
        }
        $result['lines'][] = $line;
    }
    unset($result['_last']);
    while ($result['lines'] && trim(end($result['lines'])) === '') array_pop($result['lines']);
    while ($result['lines'] && trim($result['lines'][0]) === '') array_shift($result['lines']);
    return $result;
}


/** the public methods; for an abstract class the protected ones too, since the classes that extend it call them */
function public_methods($class)
{
    $interface = $class['kind'] === 'interface';
    $abstract = $class['kind'] === 'abstract class';
    return array_values(array_filter($class['methods'], function ($m) use ($interface, $abstract) {
        if ($interface || in_array('public', $m['mods'])) return true;
        if (in_array('private', $m['mods'])) return false;
        if (in_array('protected', $m['mods'])) return $abstract;
        return true;
    }));
}

/** the first sentence of a class's doc comment, without its file-name header line */
function summary($class)
{
    $lines = parse_doc($class['doc'])['lines'];
    $text = array();
    foreach ($lines as $line) {
        $trim = trim($line);
        if ($trim === '' ) { if ($text) break; continue; }
        if (preg_match('/^[A-Za-z]+\.php$/', $trim)) continue;                         // "Route.php"
        if (preg_match('/^(Class|Attribute|Interface|Trait)\s+' . preg_quote($class['name']) . '(\s*\([\d.]+\))?\s*$/i', $trim)) continue;   // "Class Query (2.19.0)"
        if (preg_match('/^\s{2,}/', $line)) { if ($text) break; continue; }          // an indented example
        $text[] = $trim;
    }
    $s = implode(' ', $text);
    if ($s === '') return '(no doc comment)';
    if (preg_match('/^(.{20,}?(?<!\d)\.)(\s|$)/', $s, $m)) $s = $m[1];   // the first sentence
    $s = rtrim($s, ':');
    return strlen($s) > 220 ? rtrim(substr($s, 0, strrpos(substr($s, 0, 220), ' '))) . ' ...' : $s;
}

