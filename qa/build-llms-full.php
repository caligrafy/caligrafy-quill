<?php
/**
 * Builds llms-full.txt (https://llmstxt.org): every page of the wiki in one Markdown file, for coding agents and
 * documentation indexes. Pages come in the order of the wiki's _Sidebar.md, then the other pages by name. Release
 * notes are left out: the CHANGELOG has them, and old releases would teach agents APIs that changed since.
 *
 *   php qa/build-llms-full.php [../caligrafy-quill.wiki] [llms-full.txt]
 *   php qa/build-llms-full.php --check    exit 1 when llms-full.txt is not what the wiki gives (QA, release)
 *
 * Contributors only (qa/ never reaches a project). Run it after the wiki changes, before a release.
 */

$args = array_values(array_filter(array_slice($argv, 1), function ($a) { return $a !== '--check'; }));
$check = in_array('--check', $argv, true);
$root = dirname(__DIR__);
$wiki = rtrim($args[0] ?? getenv('QA_WIKI') ?: $root . '/../caligrafy-quill.wiki', '/');
$out = $args[1] ?? $root . '/llms-full.txt';

if (!is_file($wiki . '/Home.md') || !is_file($wiki . '/_Sidebar.md')) {
    fwrite(STDERR, "No wiki at $wiki (git clone https://github.com/caligrafy/caligrafy-quill.wiki.git next to this folder)\n");
    exit(2);
}

$skip = function ($page) {
    return $page === '_Sidebar' || $page === '_Footer' || str_starts_with($page, 'Release-notes');
};

// the sidebar's order: each wiki link, once, as the page name (anchors dropped, URL encoding undone)
$order = array('Home');
preg_match_all('#github\.com/caligrafy/caligrafy-quill/wiki/([^)\s\#]+)#', file_get_contents($wiki . '/_Sidebar.md'), $m);
foreach ($m[1] as $link) {
    $page = rawurldecode($link);
    if (!in_array($page, $order, true) && is_file("$wiki/$page.md") && !$skip($page)) {
        $order[] = $page;
    }
}
$others = array();
foreach (glob($wiki . '/*.md') as $file) {
    $page = basename($file, '.md');
    if (!in_array($page, $order, true) && !$skip($page)) {
        $others[] = $page;
    }
}
natsort($others);
$pages = array_merge($order, array_values($others));

$version = '';
if (preg_match("/const VERSION\s*=\s*'([^']+)'/", (string) @file_get_contents($root . '/framework/core/Framework.php'), $v)) {
    $version = ' ' . $v[1];
}

$text = "# Caligrafy Quill$version: the complete documentation\n\n"
    . "> Every page of the Caligrafy Quill wiki (https://github.com/caligrafy/caligrafy-quill/wiki) in one file, for coding\n"
    . "> agents. The short index is llms.txt; exact signatures are in claude-plugin/skills/caligrafy/reference/api-reference.md\n"
    . "> and verified pitfalls in claude-plugin/skills/caligrafy/reference/gotchas.md. Generated by qa/build-llms-full.php.\n";
foreach ($pages as $page) {
    $body = file_get_contents("$wiki/$page.md");
    $body = preg_replace('/^!\[[^\]]*\]\([^)]*banner[^)]*\)\R/m', '', $body);   // the banner image says nothing to an agent
    $body = preg_replace('/^\s*<br\s*\/?>\s*\R/m', '', $body);                  // spacing for GitHub's page only
    $body = preg_replace('/\R{3,}/', "\n\n", trim($body));
    $text .= "\n\n---\n\n<!-- Source: https://github.com/caligrafy/caligrafy-quill/wiki/" . str_replace('%2F', '/', rawurlencode($page)) . " -->\n\n" . $body . "\n";
}

if ($check) {
    $same = is_file($out) && file_get_contents($out) === $text;
    print($same ? "llms-full.txt is up to date (" . count($pages) . " pages)\n" : "llms-full.txt is out of date: php qa/build-llms-full.php\n");
    exit($same ? 0 : 1);
}
file_put_contents($out, $text);
printf("%s: %d pages, %d KB\n", basename($out), count($pages), round(strlen($text) / 1024));
