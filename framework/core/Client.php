namespace Caligrafy;

/**
 * Class Client
 * One ES module, no dependency, for the Vue apps, the Vite SPA and Node scripts: one async function per capability
 * (create_book becomes createBook) plus call(name, input) and capabilities(). It talks to Route::capabilities().
 * - In a page of the application it uses the session: the cookie, and the CSRF token it reads once from
 *   GET {prefix}. Elsewhere (Node, another origin) configure({ baseUrl, token }) sends a personal access token.
 * - A refused call throws CapabilityError with status, code (invalid, forbidden...), message and fields.
 */
class Client
{
    /**
     * The source of the module
     * @param string $prefix the uri of Route::capabilities()
     */
    public static function generate($prefix = '/capabilities')
    {
        $prefix = '/' . trim((string) $prefix, '/');
        $functions = array();
        foreach (Capabilities::all() as $name => $entry) {
            $capability = $entry['capability'];
            $schema = Capabilities::schema($name);
            $fields = array();
            foreach ((array) $schema['properties'] as $field => $property) {
                $type = array('integer' => 'number', 'number' => 'number', 'boolean' => 'boolean')[$property['type']] ?? 'string';
                $optional = in_array($field, $schema['required'] ?? array(), true) ? '' : '?';
                $fields[] = $field . $optional . ': ' . $type;
            }
            $doc = str_replace('*/', '* /', $capability->description ?: $name);
            $flags = $capability->readOnly ? 'read-only' : ($capability->destructive ? 'destructive' : 'writes');
            $access = $capability->public ? 'public' : ($capability->scope !== '' ? $capability->scope : 'signed in');
            $functions[] = "/**\n * $doc\n * Capability $name ($flags, $access)\n * @param {{" . implode(', ', $fields) . "}} [input]\n */\n"
                . 'export const ' . self::camel($name) . " = (input = {}) => call('$name', input)\n";
        }
        $runtime = <<<'JS'
// Generated by php caligrafer.php client from application/services/: run it again after changing a capability.
// One function per capability. Each returns the result, or throws a CapabilityError (status, code, message, fields).
// In a page of this application it uses the session (cookie + CSRF token); elsewhere call configure({ baseUrl, token }).

const settings = { baseUrl: '', prefix: '__PREFIX__', token: null, credentials: 'same-origin' }
let csrf = null

export class CapabilityError extends Error {
  constructor (status, error) {
    super((error && error.message) || `HTTP ${status}`)
    this.name = 'CapabilityError'
    this.status = status
    this.code = (error && error.code) || 'error'
    this.fields = (error && error.fields) || {}
  }
}

// baseUrl: the application root (default: this origin), token: a personal access token, prefix, credentials
export function configure (options = {}) {
  Object.assign(settings, options)
  csrf = null
}

async function request (method, path, body) {
  const headers = { Accept: 'application/json' }
  if (body !== undefined) headers['Content-Type'] = 'application/json'
  if (settings.token) headers.Authorization = `Bearer ${settings.token}`
  else if (method !== 'GET') headers['X-CSRF-Token'] = await csrfToken()
  const response = await fetch(settings.baseUrl + settings.prefix + path, {
    method, headers, credentials: settings.credentials, body: body === undefined ? undefined : JSON.stringify(body)
  })
  const json = await response.json().catch(() => null)
  if (!response.ok) throw new CapabilityError(response.status, json && json.error)
  return json
}

async function csrfToken () {
  if (csrf === null) csrf = (await request('GET', '')).csrf || ''
  return csrf
}

// The capabilities the caller may use, with their input schema
export async function capabilities () {
  return (await request('GET', '')).data
}

// Calls a capability by name
export async function call (name, input = {}) {
  return (await request('POST', '/' + encodeURIComponent(name), input)).data
}

JS;
        return str_replace('__PREFIX__', $prefix, $runtime) . implode("\n", $functions);
    }

    /**
     * create_book -> createBook
     */
    public static function camel($name)
    {
        return lcfirst(str_replace(' ', '', ucwords(str_replace('_', ' ', $name))));
    }
}
